import hashlib # SHA-256 등 다양한 해시 함수를 제공하는 파이썬 표준 라이브러리
import time # 블록 생성 시각(timestamp)을 기록하기 위해 사용

class Block:
    def __init__(self, index, data, previous_hash):
        self.index = index # 블록의 순서 번호 (0부터 시작, 제네시스 블록이 0)
        self.timestamp = time.time() # 블록이 생성된 시각 (유닉스 타임스탬프, 초 단위 실수)
        self.data = data # 블록에 담을 실제 내용 (거래 내역, 메시지 등 아무 데이터나 가능)
        self.previous_hash = previous_hash # 바로 이전 블록의 해시값 -> 이걸로 블록끼리 사슬처러럼 연결됨
        self.hash = self.calculate_hash() # 위 4개 정보를 조합해 이 블록만의 고유한 해시값을 계산해서 저장

    def calculate_hash(self):
        # 블록의 모든 내용을 합쳐서 해시값 하나로 만듦
        content = f"{self.index}{self.timestamp}{self.data}{self.previous_hash}"
        return hashlib.sha256(content.encode()).hexdigest()

    def __repr__(self):
        return (
            f"Block #{self.index}\n"
            f"data: {self.data}\n"
            f"prev_hash: {self.previous_hash[:16]}...\n"
            f"hash: {self.hash[:16]}...\n"
        )
    """
    * 해시 함수란?
    - 임의 길이의 입력 데이터를 받아 고정된 길이의 출력값(해시값)으로 바꿔주는 함수
    - 핵심 성질
    1. 같은 입력엔 항상 같은 출력 > "결정적"
    2. 입력이 조금만 달라져도 출력이 완전히 달라짐 > "눈사태 효과"
    3. 출력에서 입력을 역으로 알아낼 수 없음 > "단방향"
    >> 위와 같은 성질들로 인하여 "데이터가 원본 그대로인지" 검증 가능
    - 예시
    : 1글자를 넣든, 1GB짜리 파일을 넣든, SHA-256 해시 함수를 통과시키면 항상 64자리 16진수 문자열이 출력됨

    * SHA-256이란? > "무결성 검증 도구로 사용됨"
    - SHA(Secure Hash Algorithm) 계열의 해시 함수 중 하나
    - 256 비트(= 64비트 16진수) 길이의 해시값을 생성
        > 16진수 1자리 = 2진수 4비트
        > 64자리(16진수) x (글자당) 4비트 = 256비트 
    - 내부적으로는 입력 데이터를 512비트 블록 단위로 쪼갠 뒤, 여러 라운드에 걸쳐 비트 연산(AND, OR, XOR, 시프트 등)을 반복하여 최종 256 비트 결과를 만들어냄
    - 미국 NSA가 설계 + NIST가 표준화 > 비트코인을 포함한 대부분의 블록체인이 해당 알고리즘을 사용
    - SHA-256의 장점
    1. MD5/SHA-1이 뚫린 이후 검증된 대인 중 계산 속도와 보안성의 균형이 가장 좋은 선택지이기 때문
        > 한마디로, 안전성이 실전에서 아직 깨지지 않았기 때문
    2. 속도 : SHA-512보다 계산이 빨라서(32비트 환경에 최적화) 대량의 블록/거래를 처리하는 블록체인에 유리
    3. 표준화 : NIST가 공식 표준으로 채택하여 하드웨어와 라이브러리 지원이 광범위함
    4. 비트코인의 선택 효과: 비트코인이 2009년에 SHA-256을 채택한 이후, 생태계 전체가 이를 표준처럼 따라가는 관성이 있음
    
    - SHA-256 vs SHA-512
    1. SHA-256의 연산 단위(워드 크기)는 32비트로, 32비트 CPU에서는 SHA-256이 더 빠름
        : 32비트 CPU(오래된 임베디드 기기, 구형 프로세서 등)에서는 SHA-256이 더 빠릅니다. CPU가 네이티브로 32비트 연산을 하니까, SHA-256의 32비트 워드 연산이 CPU 구조와 딱 맞아떨어져요. 
        반면 SHA-512는 64비트 연산을 32비트 CPU에서 두 번에 나눠 처리해야 해서 비효율적이에요.
    2. SHA-512의 연산 단위(워드 크기)는 64비트로, 64비트 CPU에서는 SHA-512가 더 빠름
        : 반대로 요즘 대부분의 64비트 CPU(노트북, 서버)에서는 오히려 SHA-512가 SHA-512는 한 번에 더 많은 데이터(1024비트)를 처리하니까, 바이트당 비교하면 SHA-256보다 빠른 경우가 많아요. 
        라운드 수는 더 많지만, 한 라운드에서 처리하는 데이터 양도 그만큼 크기 때문에 상쇄되는 거예요.
    
    | 항목            | SHA-256 | SHA-512 |
    |-----------------|---------|---------|
    | 연산 단위(워드 크기) | 32비트   | 64비트   |
    | 라운드 수         | 64라운드 | 80라운드 |
    | 한 번에 처리하는 블록 크기 | 512비트 | 1024비트 |

    + "공식 표준이 된다"의 의미
    1. 명세가 문서로 고정된다
    - NIST(미국 국립표준기술연구소)가 SHA-256의 계산 방식을 FIPS 180-4라는 공식 문서에 정확히 적어놓음
    > "이 순서대로, 이 연산을, 이 상수값으로 하면 SHA-256이다"라고 못을 박아둔 것
    > 한국 개발자가 만든 프로그램과 미국 개발자가 만든 프로그램이 같은 데이터를 넣으면 반드시 같은 해시값이 나옴
    >> 이것이 "표준"의 가장 실용적인 의미 - "누가 구현해도 결과가 똑같다는 걸 보장하는 것"

    2. 공개적으로 검증(공격)당한다
    - 표준으로 등록되면 전 세계 암호학자들이 뚫을 수 있는지 몇 년씩 공격을 시도함
    - SHA-256은 2001년 표준화 이후 20년 넘게 이런 검증을 거쳤는데도 실용적인 공격법이 안 나옴
    - 반면, MD5, SHA-1은 이 과정에서 뚫려서 더 이상 표준으로 못 쓴다고 판단되어 폐기됨
    - 따라서 표준이라는 것은 "많은 사람이 검증했다"는 신뢰의 증거가 됨

    3. 하드웨어/소프트웨어가 이걸 기준으로 최적화된다
    - 표준이 정해지면 CPU 제조사(Intel, AMD 등)가 아예 SHA-256 계산을 위한 전용 명령어(SHA extensions)를 칩에 내장함
    - 프로그래밍 언어의 표준 라이브러리(ex) hashlib)도 이 표준에 맞춰 구현됨
    - 만약 표준이 없어 회사마다 자기식 해시 알고리즘을 썼다면, 이런 하드웨어 최적화나 라이브러리 지원은 불가능했을 것

    4. 다른 시스템들이 서로 신뢰하고 연동할 수 있게 된다 > "표준의 가장 핵심적인 존재 이유"
    - 블록체인에서 전 세계 수만 개의 노드가 서로 다른 회사가 만든  소프트웨어를 쓰고 있어도, 다들 같은 표준(SHA-256)을 따름
    > "이 블록의 해시가 맞다/틀리다"에 대해 모두가 같은 결론에 도달할 수 있음
    > if 표준이 없다면, 노드마다 계산 방식이 달라서 애초에 "합의"라는 게 성립할 수 없음

    * 제네시스 블록이란?
    - 체인의 맨 첫 번째 블록(index=0)
    - 모든 블록은 "이전 블로의 해시값"을 가져야 함 but 첫 블록은 가리킬 이전 블록이 없음
    > 관례적으로 previous_hash를 "0"와 같은 임의의 고정값으로 채워서 체인을 시작
    - 코드에서 create_genesis_block()이 이 역할을 하고 있음
    - 이후 모든 블록은 직간접적으로 제네시스 블록까지 연결됨 > 체인 전체의 "뿌리 역할"을 함

    * 유닉스 타임스탬프란?
    - 1970년 1월 1일 00:00:00 UTC를 기준(0)으로, 그 이후 몇 초가 지났는지를 숫자로 나타낸 시간 표기 방식
    - time.time()을 호출하면 현재 시각이 이 방식의 실수(float)로 반환
    - 사람이 읽기엔 불편 but 컴퓨터끼리 시간을 비교하거나 연산하기엔 훨씬 편리 > 대부분의 시스템에서 내부적으로 이 방식을 사용
    - 블록체인에서는, "이 블록이 언제 만들어졌는지"를 기록 + 이 값도 해시 계산에 포함시켜 무결성 검증 대상에 넣음

    * 이전 블록 해시값 생성과 체인 연결의 의미
    - 새 블록을 만들 때, HashChain.add_block()에서 latest.hash를 가져와서 새 블록의 previous_hash로 넘겨줌
    > latest.hash: 직전 블록이 이미 갖고 있는 해시값
    >> "생성"한다기보다는, 직전 블록이 만들어질 때 이미 계산해 둔 해시값을 그대로 물려받는 것

    - 리스트의 노드 추가 및 삭제와의 유사점과 차이점
    1. 유사점: 새 항목을 맨 끝에 붙이는 방식이 구조적으로 동일 (뒤쪽 포인터 or 해시를 채워서 연결)
    1) 연결 리스트에서 각 노드, "다음 주소를 가리키는 포인터(주로)"를 가짐
    2) 블록체인, 방향만 반대로하여 각 블록이 "이전 블록을 가리키는 값(해시)"을 가짐
    
    2. 차이점: "가리키는 값"의 성격
    > 연결 리스트
    1) 연결에 쓰는 값: 메모리 주소(포인터)
    2) 값의 의미: 위치 정보 > "어디에 있는지"
    3) 중간 노드 데이터를 바꿀 경우: 포인터는 그대로 유효함 and 그냥 값만 바뀜
    4) 중간 노드를 삭제하는 경우: 앞뒤 포인터만 이어붙이면 자연스럽게 삭제 가능
    > 해시 체인
    1) 연결에 쓰는 값: 이전 블록의 해시값
    2) 값의 의미: 내용의 지문 > "무엇이었는지"
    3) 중간 노드 데이터를 바꿀 경우: 포인터 역할을 하는 해시갑 자체가 완전히 달라짐 and 다음 블록과 연결이 끊김
    4) 중간 노드를 삭제하는 경우: 중간 블록을 깔끔하게 삭제하는 것이 사실상 불가능
        > B를 없애면 C의 previous_hash가 가리키는 대상이 사라짐 > 검증 로직이 즉시 연결 끊김을 잡아냄
        >> 삭제하려면 B 이후의 모든 블록을 처음부터 다시 계산하여 새로 만들어야 함
        >>>> "블록체인은 한 번 기록되면 사실상 수정 및 삭제가 불가능하다고 말하는 이유" "immutability"
    5) 결론: 구조는 연결 리스트, 목적은 위변조 탐지
        = "어디에 있는지"를 추적하는 자료구조 + "내용이 그대로인지"를 검증하는 기능을 얹음

    * f-string이란? + ...이 앞에 붙는 이유
    - f"": 파이썬의 f-string(포맷 문자열) 문법으로, 문자열 앞에 f를 붙이면 중괄호 {} 안에 변수나 표현식을 넣어 값을 문자열에 끼워 넣을 수 있음
    ex)
    name = "Alice"
    print(f"안녕, {name}!") # 안녕, Alice!

    - ...이 앞에 붙는 이유
    : 이 뒤에 생략된 내용이 있다는 것을 나타내려는 관례적인 표시


    * 네 가지 정보를 조합해 해시값을 계산 및 저장하는 방식
    - 과정:
    1. 문자열 결합
    : 네 값(index, timestamp, data, previous_hash)을 f-string으로 순서대로 이어붙임 > 한 덩어리의 문자열이 만들어짐
    2. 바이트 인코딩
    : hashlib.sha256()은 문자열이 아닌 바이트(byte) 타입을 요구 > .encode()로 문자열을 UTF-8 바이트로 변환
    3. 해시 계산
    : hashlib.256()이 변환된 바이트 데이터를 받아 SHA-256 알고리즘을 적용한 해시 객체를 만듦
    4. 16진수 문자열로 변환
    : .hexdigest()가 해시 계산 결과(원래는 바이너리 데이터)를 사람이 읽을 수 있는 64자리 16진수 문자열로 바꿔줌
    5. 저장
    : 변환된 문자열인 결과값이 __init__에서 self.hash에 저장됨
    - 네 값을 합치는 이유: 4개의 값 중 하나라도 값이 바뀌면 content 문자열 전체가 달라지고, 따라서 최종 해시값도 완전히 달라지기 떄문
    > "이 블록의 지문은 index, 생성 시각, 데이터, 이전 해시 이 네 가지에 모두 의존한다"는 걸 보장하는 설계

    * 해시값을 앞 16자리만 잘라서 보여주는 이유
    - 사람이 콘솔에서 보기 편하기 위한 표시상의 축약으로, 실제 검증 로직(is_valid())에서는 전체 64자리를 다 비교하기 때문에 정확도에 영향이 없음
    (16자리를 고른 것은 특별한 규칙이 아닌, "구분 가능할 정도로 충분히 길면서 지저분하지 않은 적당한 길이를 관례적으로 사용한 것)
    """

    